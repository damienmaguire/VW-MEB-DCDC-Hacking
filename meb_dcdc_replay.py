    print(f"Duration: {FRAMES[-1][0] / 1e6:.1f}s")
    print("Starting replay on can0...")
    print("Ctrl-C to stop")
    
    bus = can.interface.Bus(channel='can0', interface='socketcan', fd=True)
    
    t0 = time.monotonic()
    
    try:
        for i, (t_us, can_id, data) in enumerate(FRAMES):
            t_target = t0 + t_us / 1e6
            now = time.monotonic()
            
            if t_target > now:
                time.sleep(t_target - now)
            
            bus.send(can.Message(
                arbitration_id=can_id,
                data=bytes(data),
                is_extended_id=False,
                is_fd=True,
                bitrate_switch=True
            ))
            
            if i % 100 == 0:
                print(f"  Frame {i}/{len(FRAMES)}")
        
        print("Replay complete.")
    
    except KeyboardInterrupt:
        print("\nStopped.")
    finally:
        bus.shutdown()

